'''Analyze correlations between adaptive calibration deviations and localization gains across KAIST sequences.

The script consumes the CSV files generated by process_kaist_pipeline_results.py:

    <dataset_root>/pipeline_results_summary/<lidar_mode>/plots_metrics/
        localization_metrics.csv
        calibration_deviations_per_dataset.csv

For each free calibration variable/deviation magnitude, it computes Spearman's
rank correlation against the per-sequence localization gain of each localization
metric. Positive localization gain means lower error with calibration.

The analysis is sequence-balanced: every dataset contributes one calibration
deviation value and one localization-gain value.

Default output:

    <dataset_root>/pipeline_results_summary/<lidar_mode>/plots_metrics/spearman_correlations/
        spearman_correlations.csv
        spearman_rho_matrix.csv
        spearman_heatmap.png
        scatter/
            ...

Example:

    python analyze_kaist_calibration_correlations.py /mnt/d/Downloads/MobRobLab/KAISTDataset

Example for RMSE:

    python analyze_kaist_calibration_correlations.py /mnt/d/Downloads/MobRobLab/KAISTDataset --statistic rmse

Example without scatter plots:

    python analyze_kaist_calibration_correlations.py /mnt/d/Downloads/MobRobLab/KAISTDataset --no-scatter-plots
'''

from __future__ import annotations

import argparse
from pathlib import Path
import re
import warnings
from typing import Any

import matplotlib

matplotlib.use('Agg')

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import spearmanr


##################################################
# Display definitions
##################################################


LOCALIZATION_METRIC_LABELS = {
    'absolute_translation_m': 'Absolute translation',
    'absolute_rotation_deg': 'Absolute orientation',
    'translation_rpe_m': 'Translation RPE',
    'rotation_rpe_deg': 'Rotation RPE',
    'translation_rte_m': 'Translation RTE',
    'rotation_rte_deg': 'Rotation RTE',
}


##################################################
# Generic helpers
##################################################


def natural_sort_key(value: str) -> list[Any]:
    '''Return a natural sorting key so Urban8 appears before Urban13.'''

    return [int(component) if component.isdigit() else component.lower() for component in re.split(r'(\d+)', str(value))]


def resolve_plots_metrics_directory(dataset_root: Path, lidar_mode: str, requested_path: Path | None) -> Path:
    '''Resolve the directory containing the localization and calibration CSV files.'''

    if requested_path is None:
        return (dataset_root / 'pipeline_results_summary' / lidar_mode / 'plots_metrics').resolve()

    path = requested_path.expanduser()

    if not path.is_absolute():
        path = dataset_root / path

    return path.resolve()


def predictor_label(variable: str, deviation_type: str) -> str:
    '''Build a compact human-readable calibration predictor label.'''

    variable_short = str(variable).replace(':extrinsic', '').replace(':time_offset', '').replace(':gyro_bias', '')

    suffixes = {
        'extrinsic_rotation_deg': 'rotation',
        'extrinsic_translation_m': 'translation',
        'time_offset_ms': 'time offset',
        'gyro_bias_radps': 'bias norm',
        'gyro_bias_x_radps': 'bias |X|',
        'gyro_bias_y_radps': 'bias |Y|',
        'gyro_bias_z_radps': 'bias |Z|',
    }

    suffix = suffixes.get(str(deviation_type), str(deviation_type))

    return f'{variable_short} {suffix}'


##################################################
# Input preparation
##################################################


def load_localization_gains(path: Path, statistic: str) -> pd.DataFrame:
    '''Load one selected localization statistic from localization_metrics.csv.'''

    if not path.is_file():
        raise FileNotFoundError(f'Localization metrics CSV was not found: {path}')

    dataframe = pd.read_csv(path)
    required_columns = {'dataset', 'metric', 'statistic', 'relative_gain_percent'}
    missing_columns = sorted(required_columns.difference(dataframe.columns))

    if missing_columns:
        raise ValueError(f'Localization metrics CSV is missing columns: {", ".join(missing_columns)}')

    selected = dataframe[dataframe['statistic'].astype(str) == statistic].copy()

    if selected.empty:
        available_statistics = sorted(dataframe['statistic'].astype(str).unique())
        raise ValueError(f'Statistic {statistic!r} was not found in {path}. Available: {available_statistics}')

    selected['relative_gain_percent'] = pd.to_numeric(selected['relative_gain_percent'], errors='coerce')
    selected = selected[np.isfinite(selected['relative_gain_percent'])]

    return selected[['dataset', 'metric', 'relative_gain_percent']]


def load_calibration_deviations(path: Path, include_fixed: bool) -> pd.DataFrame:
    '''Load one mean calibration deviation per dataset and calibration quantity.'''

    if not path.is_file():
        raise FileNotFoundError(f'Calibration deviation CSV was not found: {path}')

    dataframe = pd.read_csv(path)
    required_columns = {'dataset', 'variable', 'deviation_type', 'mean'}
    missing_columns = sorted(required_columns.difference(dataframe.columns))

    if missing_columns:
        raise ValueError(f'Calibration deviation CSV is missing columns: {", ".join(missing_columns)}')

    if 'fixed' in dataframe.columns and not include_fixed:
        fixed_values = dataframe['fixed']

        if fixed_values.dtype == bool:
            dataframe = dataframe[~fixed_values].copy()
        else:
            fixed_as_text = fixed_values.astype(str).str.lower()
            dataframe = dataframe[~fixed_as_text.isin({'true', '1', 'yes'})].copy()

    dataframe['mean'] = pd.to_numeric(dataframe['mean'], errors='coerce')
    dataframe = dataframe[np.isfinite(dataframe['mean'])].copy()
    dataframe['predictor'] = [predictor_label(variable, deviation_type) for variable, deviation_type in zip(dataframe['variable'], dataframe['deviation_type'])]

    return dataframe[['dataset', 'variable', 'deviation_type', 'predictor', 'mean']]


##################################################
# Spearman analysis
##################################################


def calculate_spearman_correlations(localization_dataframe: pd.DataFrame, calibration_dataframe: pd.DataFrame, min_datasets: int) -> pd.DataFrame:
    '''Calculate Spearman correlation for every calibration predictor / localization metric pair.'''

    rows = []
    predictor_names = sorted(calibration_dataframe['predictor'].unique())
    metric_names = [metric_name for metric_name in LOCALIZATION_METRIC_LABELS if metric_name in set(localization_dataframe['metric'])]

    for predictor_name in predictor_names:
        calibration_selected = calibration_dataframe[calibration_dataframe['predictor'] == predictor_name][['dataset', 'variable', 'deviation_type', 'mean']].copy()

        for metric_name in metric_names:
            localization_selected = localization_dataframe[localization_dataframe['metric'] == metric_name][['dataset', 'relative_gain_percent']].copy()
            merged = calibration_selected.merge(localization_selected, on='dataset', how='inner')
            merged = merged[np.isfinite(merged['mean']) & np.isfinite(merged['relative_gain_percent'])].copy()

            if len(merged) < min_datasets:
                continue

            calibration_values = merged['mean'].to_numpy(dtype=float)
            gain_values = merged['relative_gain_percent'].to_numpy(dtype=float)

            if np.allclose(calibration_values, calibration_values[0]) or np.allclose(gain_values, gain_values[0]):
                rho = np.nan
                p_value = np.nan
            else:
                result = spearmanr(calibration_values, gain_values, nan_policy='omit')
                rho = float(result.statistic)
                p_value = float(result.pvalue)

            rows.append({
                'predictor': predictor_name,
                'variable': str(merged['variable'].iloc[0]),
                'deviation_type': str(merged['deviation_type'].iloc[0]),
                'metric': metric_name,
                'metric_label': LOCALIZATION_METRIC_LABELS.get(metric_name, metric_name),
                'datasets': int(len(merged)),
                'spearman_rho': rho,
                'p_value': p_value,
                'calibration_deviation_mean': float(np.mean(calibration_values)),
                'localization_gain_mean_percent': float(np.mean(gain_values)),
                'dataset_names': ','.join(sorted(merged['dataset'].astype(str).tolist(), key=natural_sort_key)),
            })

    dataframe = pd.DataFrame(rows)

    if dataframe.empty:
        raise RuntimeError('No Spearman correlations could be calculated. Check that the calibration and localization CSVs contain overlapping datasets.')

    dataframe['abs_spearman_rho'] = np.abs(dataframe['spearman_rho'])
    dataframe = dataframe.sort_values(['abs_spearman_rho', 'predictor', 'metric'], ascending=[False, True, True]).reset_index(drop=True)

    return dataframe


##################################################
# Plotting
##################################################


def plot_spearman_heatmap(correlation_dataframe: pd.DataFrame, output_path: Path, dpi: int) -> None:
    '''Plot the Spearman rho matrix for all available calibration predictors and localization metrics.'''

    pivot = correlation_dataframe.pivot(index='predictor', columns='metric', values='spearman_rho')
    metric_names = [metric_name for metric_name in LOCALIZATION_METRIC_LABELS if metric_name in pivot.columns]
    pivot = pivot.reindex(columns=metric_names)
    predictor_names = pivot.index.tolist()
    values = pivot.to_numpy(dtype=float)

    fig_width = max(10.0, 1.55 * len(metric_names))
    fig_height = max(6.0, 0.65 * len(predictor_names) + 2.0)
    fig, axis = plt.subplots(figsize=(fig_width, fig_height))

    image = axis.imshow(values, aspect='auto', vmin=-1.0, vmax=1.0)
    colorbar = fig.colorbar(image, ax=axis)
    colorbar.set_label('Spearman rho')

    axis.set_xticks(np.arange(len(metric_names)))
    axis.set_xticklabels([LOCALIZATION_METRIC_LABELS.get(metric_name, metric_name) for metric_name in metric_names], rotation=35, ha='right')
    axis.set_yticks(np.arange(len(predictor_names)))
    axis.set_yticklabels(predictor_names)
    axis.set_title('Calibration deviation vs localization gain\nPositive rho: larger deviation is associated with larger localization improvement')

    for row_index in range(values.shape[0]):
        for column_index in range(values.shape[1]):
            value = values[row_index, column_index]

            if np.isfinite(value):
                axis.text(column_index, row_index, f'{value:.2f}', ha='center', va='center')

    fig.tight_layout()
    fig.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)


def plot_top_scatter_correlations(correlation_dataframe: pd.DataFrame, localization_dataframe: pd.DataFrame, calibration_dataframe: pd.DataFrame, output_dir: Path, count: int, dpi: int) -> None:
    '''Save scatter plots for the strongest absolute Spearman correlations.'''

    if count <= 0:
        return

    output_dir.mkdir(parents=True, exist_ok=True)
    selected_correlations = correlation_dataframe[np.isfinite(correlation_dataframe['spearman_rho'])].head(count)

    for rank, (_, correlation_row) in enumerate(selected_correlations.iterrows(), start=1):
        predictor_name = str(correlation_row['predictor'])
        metric_name = str(correlation_row['metric'])
        calibration_selected = calibration_dataframe[calibration_dataframe['predictor'] == predictor_name][['dataset', 'mean']]
        localization_selected = localization_dataframe[localization_dataframe['metric'] == metric_name][['dataset', 'relative_gain_percent']]
        merged = calibration_selected.merge(localization_selected, on='dataset', how='inner')
        merged = merged[np.isfinite(merged['mean']) & np.isfinite(merged['relative_gain_percent'])].copy()

        fig, axis = plt.subplots(figsize=(7.5, 5.5))
        axis.scatter(merged['mean'].to_numpy(dtype=float), merged['relative_gain_percent'].to_numpy(dtype=float))

        for _, row in merged.iterrows():
            axis.annotate(str(row['dataset']), (float(row['mean']), float(row['relative_gain_percent'])), xytext=(4, 4), textcoords='offset points', fontsize=8)

        axis.axhline(0.0, linewidth=1.0)
        axis.set_xlabel(f'{predictor_name} deviation')
        axis.set_ylabel('localization gain [%]')
        axis.set_title(f'{LOCALIZATION_METRIC_LABELS.get(metric_name, metric_name)}\nSpearman rho={correlation_row["spearman_rho"]:.3f}, p={correlation_row["p_value"]:.3g}, N={int(correlation_row["datasets"])}')
        axis.grid(True, alpha=0.25)

        safe_predictor_name = re.sub(r'[^A-Za-z0-9_.-]+', '_', predictor_name).strip('_')
        safe_metric_name = re.sub(r'[^A-Za-z0-9_.-]+', '_', metric_name).strip('_')
        output_path = output_dir / f'{rank:02d}_{safe_predictor_name}__{safe_metric_name}.png'

        fig.tight_layout()
        fig.savefig(output_path, dpi=dpi, bbox_inches='tight')
        plt.close(fig)


##################################################
# Argument parser
##################################################


def build_argument_parser() -> argparse.ArgumentParser:
    '''Construct the command-line interface.'''

    parser = argparse.ArgumentParser(description='Analyze Spearman correlations between adaptive calibration deviation and localization gain across KAIST sequences.')
    parser.add_argument('dataset_root', type=Path, help='KAISTDataset root containing UrbanXX directories and pipeline_results_summary.')
    parser.add_argument('--lidar-mode', choices=('poses', 'odometry'), default='poses', help='LiDAR result mode.')
    parser.add_argument('--plots-metrics-dir', type=Path, default=None, help='Directory containing localization_metrics.csv and calibration_deviations_per_dataset.csv. Default: <dataset_root>/pipeline_results_summary/<lidar_mode>/plots_metrics.')
    parser.add_argument('--statistic', type=str, default='median', help='Localization statistic to correlate, for example median, rmse, or p90.')
    parser.add_argument('--include-fixed', action=argparse.BooleanOptionalAction, default=False, help='Include fixed calibration variables. They are normally omitted because zero/constant deviations have undefined rank correlation.')
    parser.add_argument('--min-datasets', type=int, default=5, help='Minimum number of overlapping datasets required for one correlation.')
    parser.add_argument('--scatter-plots', action=argparse.BooleanOptionalAction, default=True, help='Save scatter plots for the strongest correlations.')
    parser.add_argument('--top-scatter', type=int, default=12, help='Number of strongest absolute correlations to plot.')
    parser.add_argument('--dpi', type=int, default=180, help='Saved plot resolution.')

    return parser


##################################################
# Main processing
##################################################


def run(args: argparse.Namespace) -> None:
    '''Load aggregate CSVs, calculate Spearman correlations, and save tables and plots.'''

    dataset_root = args.dataset_root.expanduser().resolve()

    if not dataset_root.is_dir():
        raise FileNotFoundError(f'Dataset root does not exist: {dataset_root}')

    plots_metrics_dir = resolve_plots_metrics_directory(dataset_root, args.lidar_mode, args.plots_metrics_dir)
    localization_path = plots_metrics_dir / 'localization_metrics.csv'
    calibration_path = plots_metrics_dir / 'calibration_deviations_per_dataset.csv'
    output_dir = plots_metrics_dir / 'spearman_correlations'
    output_dir.mkdir(parents=True, exist_ok=True)

    localization_dataframe = load_localization_gains(localization_path, args.statistic)
    calibration_dataframe = load_calibration_deviations(calibration_path, args.include_fixed)
    correlation_dataframe = calculate_spearman_correlations(localization_dataframe, calibration_dataframe, args.min_datasets)

    correlation_path = output_dir / 'spearman_correlations.csv'
    rho_matrix_path = output_dir / 'spearman_rho_matrix.csv'
    heatmap_path = output_dir / 'spearman_heatmap.png'

    correlation_dataframe.to_csv(correlation_path, index=False, float_format='%.10g')
    rho_matrix = correlation_dataframe.pivot(index='predictor', columns='metric', values='spearman_rho')
    rho_matrix.to_csv(rho_matrix_path, float_format='%.10g')
    plot_spearman_heatmap(correlation_dataframe, heatmap_path, args.dpi)

    if args.scatter_plots:
        plot_top_scatter_correlations(correlation_dataframe, localization_dataframe, calibration_dataframe, output_dir / 'scatter', args.top_scatter, args.dpi)

    print()
    print('Spearman calibration-deviation analysis')
    print('=======================================')
    print(f'statistic: {args.statistic}')
    print(f'datasets in localization table: {len(localization_dataframe["dataset"].unique())}')
    print(f'datasets in calibration table:  {len(calibration_dataframe["dataset"].unique())}')
    print()
    print('Strongest correlations')
    print('----------------------')

    display_columns = ['predictor', 'metric_label', 'datasets', 'spearman_rho', 'p_value']

    with pd.option_context('display.max_rows', 20, 'display.width', 160):
        print(correlation_dataframe[display_columns].head(20).to_string(index=False))

    print()
    print('Saved outputs')
    print('-------------')
    print(correlation_path)
    print(rho_matrix_path)
    print(heatmap_path)

    if len(localization_dataframe['dataset'].unique()) < 15:
        warnings.warn('The number of KAIST sequences is small. Treat Spearman rho as an exploratory effect-size diagnostic; p-values will have low power and should not be over-interpreted.')


##################################################
# Entrypoint
##################################################


def main() -> None:
    '''Parse arguments and run the correlation analysis.'''

    parser = build_argument_parser()
    args = parser.parse_args()

    if args.min_datasets < 3:
        parser.error('--min-datasets must be at least 3.')

    if args.top_scatter < 0:
        parser.error('--top-scatter must be non-negative.')

    if args.dpi <= 0:
        parser.error('--dpi must be positive.')

    run(args)


if __name__ == '__main__':
    main()

